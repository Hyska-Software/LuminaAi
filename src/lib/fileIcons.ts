/** GitHub Actions workflows live in a fixed directory — the only path rule. */
const GITHUB_WORKFLOW_PATH = /(?:^|[\\/])\.github[\\/]workflows[\\/][^\\/]+\.ya?ml$/i;

/** Lowercased last path segment (`src/app.ts` → `app.ts`; handles `\` too). */
function basename(pathOrName: string): string {
  const withoutTrailingSlash = pathOrName.replace(/[\\/]+$/, '');
  const separator = Math.max(withoutTrailingSlash.lastIndexOf('/'), withoutTrailingSlash.lastIndexOf('\\'));
  return (separator >= 0 ? withoutTrailingSlash.slice(separator + 1) : withoutTrailingSlash).toLowerCase();
}

/** Text after the last dot; empty for dotfiles and extensionless names. */
function extensionOf(name: string): string {
  const dot = name.lastIndexOf('.');
  return dot > 0 && dot < name.length - 1 ? name.slice(dot + 1) : '';
}

/**
 * Icon id for a workspace path or bare file name. Never throws and never
 * returns `null`: unknown types fall back to the neutral `file` mark. Directory
 * paths are accepted but resolve like files — callers handle folders separately.
 */
export function fileIconKeyFor(pathOrName: string): FileIconKey {
  const path = typeof pathOrName === 'string' ? pathOrName.trim() : '';
  if (!path) return FILE_ICON_FALLBACK;

  if (GITHUB_WORKFLOW_PATH.test(path)) return 'github-actions-workflow';

  const name = basename(path);
  if (!name) return FILE_ICON_FALLBACK;

  if (Object.hasOwn(FILE_NAME_ICONS, name)) return FILE_NAME_ICONS[name];
  if (/\.d\.[cm]?ts$/.test(name)) return 'typescript-def';

  for (const [pattern, icon] of NAME_PATTERNS) {
    if (pattern.test(name)) return icon;
  }

  const extension = extensionOf(name);
  if (extension && Object.hasOwn(EXTENSION_ICONS, extension)) return EXTENSION_ICONS[extension];

  return FILE_ICON_FALLBACK;
}
