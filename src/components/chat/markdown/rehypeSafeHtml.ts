import type { Element, ElementContent, Properties, Root, RootContent } from 'hast';

/**
 * `rehypeSafeHtml` — allowlist sanitizer for raw HTML embedded in chat
 * Markdown (`docs/MARKDOWN.md` §3.1).
 *
 * The tree is parsed by `rehype-raw` first; this plugin then runs **before**
 * KaTeX and:
 *
 * - drops dangerous subtrees (`script`, `style`, `iframe`, `object`, `embed`,
 *   `svg`, raw `math`, form controls, media, …);
 * - unwraps unknown tags (text survives, attributes do not);
 * - strips comments, event handlers (`on*`), `style` (except `text-align` on
 *   `th`/`td`), `target`, `srcset`, unknown classes and arbitrary `data-*`;
 * - keeps only `http(s)`, `mailto:` and `#anchor` links (images: `http(s)`);
 * - preserves the attributes generated by `remark-gfm`/`remark-math` so task
 *   lists, footnote navigation, table alignment and KaTeX keep working.
 *
 * Security is structural: React never renders this HTML through `innerHTML`.
 * The default `react-markdown` URL transform still runs afterwards as defense
 * in depth.
 */

