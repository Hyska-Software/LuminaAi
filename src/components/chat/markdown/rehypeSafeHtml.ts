/** Class names generated by `remark-gfm` / `remark-math` (docs §3.1). */
const ALLOWED_CLASSES = new Set([
  'contains-task-list',
  'task-list-item',
  'footnotes',
  'data-footnote-backref',
  'sr-only',
  'math',
  'math-inline',
  'math-display',
]);

const LANGUAGE_CLASS = /^language-[a-z0-9_+#.-]{1,32}$/i;
const ID = /^[A-Za-z][A-Za-z0-9_.:-]{0,127}$/;
const CONTROL = /[\u0000-\u001f\u007f]/;
const CONTROL_CHARS = /[\u0000-\u001f\u007f]/g;
const WHITESPACE_OR_CONTROL = /[\s\u0000-\u001f\u007f]/;
const LINK_URL = /^(?:https?:\/\/[^\s\u0000-\u001f\u007f]+|mailto:[^\s\u0000-\u001f\u007f]+|#[^\u0000-\u001f\u007f]*)$/i;
const IMAGE_URL = /^https?:\/\/[^\s\u0000-\u001f\u007f]+$/i;
const TEXT_ALIGN = /^(left|center|right|justify)$/i;

const MAX_ATTRIBUTE_LENGTH = 2000;

function stringValue(value: Properties[string]): string | null {
  if (typeof value === 'string') return value;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  return null;
}

function sanitizeText(value: string | null): string | null {
  if (!value) return null;
  const text = value.replace(CONTROL_CHARS, ' ').trim();
  if (!text) return null;
  return text.slice(0, MAX_ATTRIBUTE_LENGTH);
}

function splitClasses(value: Properties[string]): string[] {
  if (typeof value === 'string') return value.split(WHITESPACE_OR_CONTROL).filter(Boolean);
  if (Array.isArray(value)) {
    return value
      .filter((entry): entry is string => typeof entry === 'string')
      .flatMap((entry) => entry.split(WHITESPACE_OR_CONTROL))
      .filter(Boolean);
  }
  return [];
}

function isAllowedClass(name: string): boolean {
  if (ALLOWED_CLASSES.has(name)) return true;
  return LANGUAGE_CLASS.test(name);
}

function sanitizeLinkUrl(value: string | null): string | null {
  if (!value) return null;
  const url = value.trim();
  if (!url || CONTROL.test(url)) return null;
  return LINK_URL.test(url) ? url : null;
}

function sanitizeImageUrl(value: string | null): string | null {
  if (!value) return null;
  const url = value.trim();
  if (!url || CONTROL.test(url)) return null;
  return IMAGE_URL.test(url) ? url : null;
}

function sanitizeIdList(value: Properties[string]): string | null {
  const raw = Array.isArray(value) ? value.filter((entry): entry is string => typeof entry === 'string').join(' ') : stringValue(value);
  if (!raw) return null;
  const ids = raw.split(WHITESPACE_OR_CONTROL).filter(Boolean);
  if (!ids.length || ids.length > 20) return null;
  return ids.every((id) => ID.test(id)) ? ids.join(' ') : null;
}

function textAlignFromStyle(value: string | null): string | null {
  if (!value) return null;
  for (const declaration of value.split(';')) {
    const [property, ...rest] = declaration.split(':');
    if (property?.trim().toLowerCase() !== 'text-align') continue;
    const candidate = rest.join(':').trim().toLowerCase();
    if (TEXT_ALIGN.test(candidate)) return candidate;
  }
  return null;
}

function textAlignFromAttribute(value: string | null): string | null {
  if (!value) return null;
  const candidate = value.trim().toLowerCase();
  return TEXT_ALIGN.test(candidate) ? candidate : null;
}

function integerValue(value: Properties[string]): number | null {
  const raw = stringValue(value);
  if (raw === null) return null;
  const parsed = Number.parseInt(raw, 10);
  return Number.isFinite(parsed) ? parsed : null;
}

function isOpenDetails(value: Properties[string]): boolean {
  if (value === true || value === '') return true;
  return typeof value === 'string' && value.toLowerCase() === 'open';
}

/**
 * Filters the properties of one element. Anything not explicitly recognized
 * is discarded — this is what removes `on*`, `style`, `target`, `srcset`, etc.
 */
function sanitizeProperties(tagName: string, properties: Properties): Properties {
  const result: Properties = {};

  for (const key of Object.keys(properties)) {
    const value = properties[key];
    if (value === null || value === undefined) continue;

    switch (key) {
      case 'className': {
        const classes = splitClasses(value).filter(isAllowedClass);
        if (classes.length) result.className = classes;
        break;
      }
      case 'id': {
        const id = stringValue(value)?.trim();
        if (id && ID.test(id)) result.id = id;
        break;
      }
      case 'href': {
        if (tagName !== 'a') break;
        const href = sanitizeLinkUrl(stringValue(value));
        if (href) result.href = href;
        break;
      }
      case 'src': {
        if (tagName !== 'img') break;
        const src = sanitizeImageUrl(stringValue(value));
        if (src) result.src = src;
        break;
      }
      case 'alt':
      case 'title': {
        const text = sanitizeText(stringValue(value));
        if (text) result[key] = text;
        break;
      }
      case 'ariaLabel': {
        const label = sanitizeText(stringValue(value));
        if (label) result.ariaLabel = label;
        break;
      }
      case 'ariaDescribedBy': {
        const ids = sanitizeIdList(value);
        if (ids) result.ariaDescribedBy = ids.split(' ');
        break;
      }
      case 'dataFootnoteRef': {
        if (tagName === 'a') result.dataFootnoteRef = '';
        break;
      }
      case 'dataFootnoteBackref': {
        if (tagName === 'a') result.dataFootnoteBackref = '';
        break;
      }
      case 'dataFootnotes': {
        if (tagName === 'section') result.dataFootnotes = '';
        break;
      }
      case 'style': {
        if (tagName !== 'th' && tagName !== 'td') break;
        const align = textAlignFromStyle(stringValue(value));
        if (align) result.style = `text-align: ${align}`;
        break;
      }
      case 'align': {
        if (tagName !== 'th' && tagName !== 'td') break;
        const align = textAlignFromAttribute(stringValue(value));
        if (align) result.style = `text-align: ${align}`;
        break;
      }
      case 'start': {
        if (tagName !== 'ol') break;
        const start = integerValue(value);
        if (start !== null && start >= 1 && start <= 1_000_000) result.start = start;
        break;
      }
      case 'open': {
        if (tagName === 'details' && isOpenDetails(value)) result.open = true;
        break;
      }
      case 'colSpan':
      case 'rowSpan': {
        if (tagName !== 'th' && tagName !== 'td') break;
        const span = integerValue(value);
        if (span !== null && span >= 1 && span <= 1000) result[key] = span;
        break;
      }
      default:
        // Everything else (`on*`, `target`, `srcset`, arbitrary `data-*`, …) is
        // intentionally dropped.
        break;
    }
  }

  return result;
}

function classListOf(element: Element): string[] {
  return splitClasses(element.properties?.className);
}

/** Raw `<input>` is only kept when it is the disabled checkbox of a GFM task list. */
function sanitizeTaskCheckbox(element: Element, ancestors: Element[]): Element | null {
  // Tight lists place the checkbox directly inside the item, loose lists wrap
  // it in a paragraph (`li.task-list-item > p > input`), so any ancestor item
  // counts — an input outside a task list is still dropped.
  const taskItem = ancestors.find(
    (ancestor) => ancestor.tagName === 'li' && classListOf(ancestor).includes('task-list-item'),
  );
  if (!taskItem) return null;
  if (stringValue(element.properties?.type)?.toLowerCase() !== 'checkbox') return null;

  const checked = element.properties?.checked === true || element.properties?.checked === '';
  const properties: Properties = { type: 'checkbox', disabled: true };
  if (checked) properties.checked = true;
  return { type: 'element', tagName: 'input', properties, children: [] };
}

function sanitizeChildren(children: RootContent[], ancestors: Element[]): ElementContent[] {
  const result: ElementContent[] = [];

  for (const child of children) {
    if (child.type === 'text') {
      result.push(child);
      continue;
    }
    if (child.type !== 'element') {
      // Comments, doctypes and leftover raw nodes are discarded.
      continue;
    }

    const tagName = child.tagName.toLowerCase();

    if (tagName === 'input') {
      const checkbox = sanitizeTaskCheckbox(child, ancestors);
      if (checkbox) result.push(checkbox);
      continue;
    }
    if (DANGEROUS_TAGS.has(tagName)) continue;

    const sanitizedChildren = sanitizeChildren(child.children, [...ancestors, child]);

    if (ALLOWED_TAGS.has(tagName)) {
      result.push({
        type: 'element',
        tagName,
        properties: sanitizeProperties(tagName, child.properties ?? {}),
        children: sanitizedChildren,
      });
      continue;
    }

    // Unknown tags are unwrapped: their text survives, their attributes do not.
    result.push(...sanitizedChildren);
  }

  return result;
}

/** rehype plugin factory (used as `[rehypeRaw, rehypeSafeHtml, rehypeKatex]`). */
export function rehypeSafeHtml() {
  return (tree: Root): undefined => {
    tree.children = sanitizeChildren(tree.children, []);
  };
}

export default rehypeSafeHtml;
