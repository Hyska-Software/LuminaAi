import assert from 'node:assert/strict';
import {
  mkdtempSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import test from 'node:test';

import { assertVersionsInSync, readVersionState } from '../shared.mjs';
import {
  applyVersion,
  buildVersionUpdates,
  compareSemver,
  isVersion,
  nextVersion,
  normalizeVersion,
} from '../version.mjs';

function createTree(version = '0.1.0', overrides = {}) {
  const root = mkdtempSync(path.join(tmpdir(), 'zylara-version-'));
  mkdirSync(path.join(root, 'src-tauri'), { recursive: true });
  mkdirSync(path.join(root, 'src/lib'), { recursive: true });
  writeFileSync(
    path.join(root, 'package.json'),
    `${JSON.stringify(
      { name: 'zylara', private: true, version, scripts: { dev: 'vite' } },
      null,
      2,
    )}\n`,
  );
  writeFileSync(
    path.join(root, 'src-tauri/tauri.conf.json'),
    `${JSON.stringify(
      { productName: 'Zylara', version, identifier: 'app.zylara.chat' },
      null,
      2,
    )}\n`,
  );
  writeFileSync(
    path.join(root, 'src-tauri/Cargo.toml'),
    `[package]\nname = "zylara"\nversion = "${overrides.cargo ?? version}"\nedition = "2021"\n\n[dependencies]\nanyhow = "1"\n`,
  );
  writeFileSync(
    path.join(root, 'src/lib/appVersion.ts'),
    `export const APP_VERSION_FALLBACK = '${overrides.ui ?? version}';\n`,
  );
  writeFileSync(
    path.join(root, 'src-tauri/Cargo.lock'),
    `# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "anyhow"\nversion = "1.0.0"\n\n[[package]]\nname = "zylara"\nversion = "${overrides.lock ?? version}"\ndependencies = [\n "anyhow",\n]\n`,
  );
  return root;
}

test('normalizes and validates versions', () => {
  assert.equal(normalizeVersion(' v0.2.0 '), '0.2.0');
  assert.equal(isVersion('0.2.0'), true);
  assert.equal(isVersion('v1.0.0'), true);
  assert.equal(isVersion('1.0.0-beta.2'), true);
  assert.equal(isVersion('1.0'), false);
  assert.equal(isVersion('1.0.0+meta'), false);
  assert.equal(isVersion('1.0.0-beta..2'), false);
  assert.equal(isVersion('1.0.0-'), false);
});

test('computes patch, minor and major bumps', () => {
  assert.equal(nextVersion('0.1.0', 'patch'), '0.1.1');
  assert.equal(nextVersion('0.1.9', 'minor'), '0.2.0');
  assert.equal(nextVersion('1.9.9', 'major'), '2.0.0');
  assert.equal(nextVersion('0.2.0-beta.1', 'patch'), '0.2.1');
  assert.throws(() => nextVersion('0.2.0', 'huge'), /bump inválido/);
});

test('compares prereleases before stable releases', () => {
  assert.equal(compareSemver('0.2.0', '0.1.0'), 1);
  assert.equal(compareSemver('0.1.0', '0.1.0'), 0);
  assert.equal(compareSemver('0.2.0-beta.1', '0.2.0'), -1);
  assert.equal(compareSemver('0.2.0', '0.2.0-rc.9'), 1);
  assert.equal(compareSemver('0.2.0-rc.10', '0.2.0-rc.9'), 1);
  assert.equal(compareSemver('0.2.0-beta', '0.2.0-alpha'), 1);
});

test('updates every version source and leaves unrelated content alone', () => {
  const root = createTree();
  const result = applyVersion(root, '0.2.0');
  assert.equal(result.applied, true);
  assert.equal(result.current, '0.1.0');
  assert.equal(result.target, '0.2.0');
  assert.deepEqual(result.files, [
    'package.json',
    'src-tauri/tauri.conf.json',
    'src-tauri/Cargo.toml',
    'src/lib/appVersion.ts',
    'src-tauri/Cargo.lock',
  ]);

  const state = readVersionState(root);
  assert.deepEqual(state, {
    packageVersion: '0.2.0',
    tauriVersion: '0.2.0',
    cargoVersion: '0.2.0',
    uiVersion: '0.2.0',
    lockVersion: '0.2.0',
  });
  assert.equal(assertVersionsInSync(root), '0.2.0');

  const packageJson = JSON.parse(readFileSync(path.join(root, 'package.json'), 'utf8'));
  assert.equal(packageJson.scripts.dev, 'vite');
  const lock = readFileSync(path.join(root, 'src-tauri/Cargo.lock'), 'utf8');
  assert.match(lock, /name = "anyhow"\nversion = "1\.0\.0"/);
  assert.match(lock, /name = "zylara"\nversion = "0\.2\.0"/);
});

test('aligns divergent sources to the requested version', () => {
  const root = createTree('0.1.0', { cargo: '0.0.9', ui: '0.0.8', lock: '0.0.7' });
  applyVersion(root, '0.2.0');
  assert.equal(assertVersionsInSync(root), '0.2.0');
});

test('accepts prerelease versions', () => {
  const root = createTree();
  applyVersion(root, '0.2.0-rc.1');
  assert.equal(assertVersionsInSync(root), '0.2.0-rc.1');
});

test('dry-run never writes files', () => {
  const root = createTree();
  const before = readFileSync(path.join(root, 'package.json'), 'utf8');
  const result = applyVersion(root, '0.2.0', { dryRun: true });
  assert.equal(result.applied, false);
  assert.equal(readFileSync(path.join(root, 'package.json'), 'utf8'), before);
  assert.equal(readVersionState(root).packageVersion, '0.1.0');
});

test('rejects equal and lower versions unless explicitly allowed', () => {
  const root = createTree();
  assert.throws(() => applyVersion(root, '0.1.0'), /já é 0\.1\.0/);
  assert.throws(() => applyVersion(root, '0.0.9'), /menor que a atual/);
  const result = applyVersion(root, '0.0.9', { allowDowngrade: true });
  assert.equal(result.applied, true);
  assert.equal(readVersionState(root).packageVersion, '0.0.9');
});

test('builds all new contents before touching the disk', () => {
  const root = createTree();
  const updates = buildVersionUpdates(root, '1.2.3');
  assert.equal(updates.length, 5);
  assert.ok(updates.every((update) => update.after.includes('1.2.3')));
  assert.equal(readVersionState(root).packageVersion, '0.1.0');
});

test('fails when a version source is missing instead of writing partially', () => {
  const root = createTree();
  writeFileSync(path.join(root, 'src/lib/appVersion.ts'), 'export const OTHER = true;\n');
  assert.throws(() => applyVersion(root, '0.2.0'), /appVersion\.ts/);
  assert.equal(readVersionState(root).packageVersion, '0.1.0');
});

test('sync check catches a UI fallback divergence', () => {
  const root = createTree();
  writeFileSync(
    path.join(root, 'src/lib/appVersion.ts'),
    "export const APP_VERSION_FALLBACK = '9.9.9';\n",
  );
  assert.throws(() => assertVersionsInSync(root), /divergentes/);
});
